"""Generate the deterministic file://-safe classic-script geometry bundle."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from dispenser_sim.viz3d.geometry_schema import canonical_json, load_geometry, source_hash


def build_bundle(data: dict) -> str:
    digest = source_hash(data)
    payload = json.dumps(data, sort_keys=True, separators=(",", ":"), ensure_ascii=False, allow_nan=False)
    return "/* Generated by tools/build_visualizer_data.py; do not edit. */\n" + f"window.DISPENSER_CONCEPT_DATA = Object.freeze(Object.assign({payload}, {{ source_sha256: '{digest}' }}));\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, default=ROOT / "docs/visualizer/concept-data.js")
    args = parser.parse_args()
    data = load_geometry(ROOT / "src/dispenser_sim/viz3d/concept_geometry.json")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(build_bundle(data), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
